"""Builds hooks/famous.ts from scripts/famous.pgn: the famous games section.

scripts/famous.pgn is the place to edit. Each game carries, beside the usual
tags, `Id` (a short slug), `Name` (what the list calls it), `Source` (the page
its moves and blurb were checked against) and `Blurb` (two or three sentences
on why it is famous). Every game is replayed with python-chess, so a move that
is not legal stops the build:
  python3 scripts/build_famous.py scripts/famous.pgn > hooks/famous.ts
"""
import sys

import chess
import chess.pgn

REQUIRED = ["Id", "Name", "White", "Black", "Event", "Date", "Result", "Source", "Blurb"]


def quote(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main():
    games = []
    seen = set()
    with open(sys.argv[1], encoding="utf-8") as pgn:
        while (game := chess.pgn.read_game(pgn)) is not None:
            missing = [tag for tag in REQUIRED if not game.headers.get(tag)]
            if missing:
                sys.exit(f"{game.headers.get('Id', '?')}: missing {', '.join(missing)}")
            if game.errors:
                sys.exit(f"{game.headers['Id']}: {game.errors[0]}")
            if game.headers["Id"] in seen:
                sys.exit(f"{game.headers['Id']}: used twice")
            seen.add(game.headers["Id"])
            if game.headers["Result"] not in ("1-0", "0-1", "1/2-1/2"):
                sys.exit(f"{game.headers['Id']}: result {game.headers['Result']}")
            board = game.board()
            sans = []
            for move in game.mainline_moves():
                sans.append(board.san(move))
                board.push(move)
            if board.is_checkmate() and game.headers["Result"] != ("1-0" if board.turn == chess.BLACK else "0-1"):
                sys.exit(f"{game.headers['Id']}: ends in mate, but the result says otherwise")
            games.append((game.headers, sans))

    rows = []
    for headers, sans in games:
        rows.append(
            "  {\n"
            f"    id: {quote(headers['Id'])},\n"
            f"    name: {quote(headers['Name'])},\n"
            f"    white: {quote(headers['White'])},\n"
            f"    black: {quote(headers['Black'])},\n"
            f"    event: {quote(headers['Event'])},\n"
            f"    year: {int(headers['Date'][:4])},\n"
            f"    result: {quote(headers['Result'])},\n"
            f"    blurb: {quote(headers['Blurb'])},\n"
            f"    source: {quote(headers['Source'])},\n"
            f"    moves: {quote(' '.join(sans))},\n"
            "  },"
        )
    print(f"""// Generated by scripts/build_famous.py from scripts/famous.pgn: edit the PGN,
// not this file. Each game's moves and blurb were checked against its source.

export type FamousGame = {{
  id: string
  /** What the list calls it. */
  name: string
  white: string
  black: string
  event: string
  year: number
  result: '1-0' | '0-1' | '1/2-1/2'
  /** Why it is famous, in two or three sentences. */
  blurb: string
  /** The page the moves and blurb were checked against. */
  source: string
  /** The moves in SAN, from the starting position, separated by spaces. */
  moves: string
}}

export const FAMOUS: FamousGame[] = [
{chr(10).join(rows)}
]""")
    print(f"{len(games)} games", file=sys.stderr)


if __name__ == "__main__":
    main()
