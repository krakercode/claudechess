"""Builds hooks/puzzles.ts from a PGN of positions taken from real games.

Each game in the PGN starts from a position (a FEN tag) with the side that went
on to win to move, and gives the moves that were played. The puzzle is the
longest start of that line in which every move of the winner is the engine's
choice and clearly better than any other, cut to end on the winner's move.
Positions where that leaves no clear win are dropped. The rest are rated by how
hard the engine finds the first move and how long and quiet the line is, and
split into thirds: easy, medium and hard.

The source is the PGN in the chess-console-puzzles npm package (MIT):
  npm pack chess-console-puzzles && tar xzf chess-console-puzzles-*.tgz
  python3 scripts/build_puzzles.py package/assets/puzzles/puzzles_Oli1970.pgn > hooks/puzzles.ts
"""
import multiprocessing
import re
import sys

import chess
import chess.engine
import chess.pgn

from check_puzzles import LEVELS, check, open_engine, solver_move_problem

HEADER = """// Generated by scripts/build_puzzles.py from positions in real games, and
// checked with Stockfish by scripts/check_puzzles.py: at each of the solver's
// moves the one in the line is the engine's choice and clearly the best.
// Ordered from easiest to hardest.

export type Level = 'easy' | 'medium' | 'hard'

export type Puzzle = {
  title: string
  level: Level
  /** The game the position comes from. */
  game: string
  fen: string
  /** The solution line in UCI, the person's moves and the replies alternating. */
  moves: string[]
  /** The same line in SAN. */
  san: string[]
}

export const PUZZLES: Puzzle[] = """


def surname(name):
    return name.split(",")[0].strip()


def credit(headers):
    event = re.sub(r"\s+", " ", headers.get("Event", "")).strip(" ?")
    year = headers.get("Date", "????")[:4]
    has_year = re.search(r"\b(1[89]|20)\d\d\b", event)
    where = event if has_year or not year.isdigit() else f"{event} {year}".strip()
    return f"{surname(headers['White'])} vs {surname(headers['Black'])}, {where}"


def find_depth(engine, board, move):
    """The shallowest depth from which the engine keeps choosing the move."""
    found = None
    for depth in range(1, 21):
        engine.configure({"Clear Hash": None})
        best = engine.analyse(board, chess.engine.Limit(depth=depth))["pv"][0]
        if best == move:
            found = found or depth
        else:
            found = None
    return found or 21


def candidate(engine, game):
    board = game.board()
    solver = board.turn
    kept = []
    for move in game.mainline_moves():
        if board.turn == solver and solver_move_problem(engine, board, move, 0):
            break
        kept.append(move)
        board.push(move)
    while kept and len(kept) % 2 == 0:
        kept.pop()
    if not kept:
        return None
    start = game.board()
    end = start.copy()
    for move in kept:
        end.push(move)
    solver_moves = (len(kept) + 1) // 2
    puzzle = {
        "title": f"Mate in {solver_moves}" if end.is_checkmate() else "Find the win",
        "level": "easy",
        "game": credit(game.headers),
        "fen": start.fen(),
        "moves": [move.uci() for move in kept],
        "san": [],
    }
    for move in kept:
        puzzle["san"].append(start.san(move))
        start.push(move)
    return puzzle


def difficulty(engine, puzzle):
    board = chess.Board(puzzle["fen"])
    quiet = 0
    for ply, uci in enumerate(puzzle["moves"]):
        move = chess.Move.from_uci(uci)
        if ply % 2 == 0 and not (board.is_capture(move) or board.gives_check(move)):
            quiet += 1
        board.push(move)
    first = chess.Move.from_uci(puzzle["moves"][0])
    solver_moves = (len(puzzle["moves"]) + 1) // 2
    return find_depth(engine, chess.Board(puzzle["fen"]), first) + 3 * (solver_moves - 1) + 2 * quiet


def rate(game):
    """The puzzle in the game and its difficulty score, or why there is none."""
    engine = open_engine()
    try:
        puzzle = candidate(engine, game)
        problem = "nothing clear" if puzzle is None else check(engine, puzzle)
        if problem:
            return None, f"dropped {game.headers.get('FEN')}: {problem}"
        return (difficulty(engine, puzzle), puzzle), None
    finally:
        engine.quit()


def main():
    games = []
    with open(sys.argv[1]) as pgn:
        while (game := chess.pgn.read_game(pgn)) is not None:
            games.append(game)
    rated = []
    with multiprocessing.Pool() as pool:
        for result, problem in pool.imap(rate, games):
            if problem:
                print(problem, file=sys.stderr)
            else:
                rated.append(result)

    rated.sort(key=lambda pair: pair[0])
    for rank, (_, puzzle) in enumerate(rated):
        puzzle["level"] = LEVELS[rank * len(LEVELS) // len(rated)]
    print(f"{len(rated)} of {len(games)} positions make puzzles", file=sys.stderr)
    print(HEADER + ts_list([puzzle for _, puzzle in rated]))


def ts_list(puzzles):
    def quote(text):
        return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"

    def strings(items):
        return "[" + ", ".join(quote(item) for item in items) + "]"

    rows = []
    for puzzle in puzzles:
        rows.append(
            "  {\n"
            f"    title: {quote(puzzle['title'])},\n"
            f"    level: {quote(puzzle['level'])},\n"
            f"    game: {quote(puzzle['game'])},\n"
            f"    fen: {quote(puzzle['fen'])},\n"
            f"    moves: {strings(puzzle['moves'])},\n"
            f"    san: {strings(puzzle['san'])},\n"
            "  },"
        )
    return "[\n" + "\n".join(rows) + "\n]"


if __name__ == "__main__":
    main()
